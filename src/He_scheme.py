def soot_lower_omega(omega_snw, wvl, mss_cnc_sot3, soot_density, Rv):
    # soot_density=1.49
    # Rv = 0.045
    # Parameterization coefficients for BC-induced enhancement in snow single-scattering coalbedo
    # Eq. 8b & Table 4 in He et al., 2017 J. Climate
    # lambda>1.2um, no BC enhancement, enhancement ratio = 1.0
    R_wvl = [0.20, 0.25, 0.30, 0.33, 0.36, 0.40, 0.44, 0.48, 0.52, 0.57, 0.64, 0.69, 0.75, 0.78,
             0.87, 1.00, 1.20, 5.00]  # wavelength (um) division point
    R_d0 = [2.48045E0,4.70305E+00, 4.68619E+00, 4.67369E+00, 4.65040E+00, 2.40364E+00,
            7.95408E-01, 2.92745E-01, 8.63396E-02, 2.76299E-02, 1.40864E-02,
            8.65705E-03, 6.12971E-03, 4.45697E-03, 3.06648E-02, 7.96544E-01, 1.0, 1.0]
    R_d1 = [9.77209E-01,9.73317E-01, 9.79650E-01, 9.84579E-01, 9.93537E-01, 9.95955E-01,
            9.95218E-01, 9.74284E-01, 9.81193E-01, 9.81239E-01, 9.55515E-01,
            9.10491E-01, 8.74196E-01, 8.27238E-01, 4.82870E-01, 4.36649E-02, 0.0, 0.0]
    R_d2 = [3.95960E-1,2.04820E-01, 2.07410E-01, 2.09390E-01, 2.13030E-01, 4.18570E-01,
            1.29682E+00, 3.75514E+00, 1.27372E+01, 3.93293E+01, 8.78918E+01,
            1.86969E+02, 3.45600E+02, 7.08637E+02, 1.41067E+03, 2.57288E+02, 1.0, 1.0]

    # center point for wavelength band
    R_wvl_center = [0.225,0.275, 0.315, 0.345, 0.380, 0.420, 0.460, 0.500, 0.545,
                    0.605, 0.665, 0.720, 0.765, 0.825, 0.935, 1.10, 3.10, 5.10]

    poly_m = [-0.7398, -0.1182, -0.0020]
    poly_n = [-0.0077, -0.1448, -0.3252]
    mono_m = [-0.8724, -0.1866, -0.0046]
    mono_n = [-0.0072, -0.1918, -0.5177]
    m_wvl = mono_m
    n_wvl = mono_n
    # BC density adjustment
    mss_cnc_sot3 = mss_cnc_sot3 * 1.7 / soot_density

    # Eq. 8b in He et al.2017,JC
    R_1_omega_tmp = R_d0 * (mss_cnc_sot3 + np.array(R_d2))**np.array(R_d1)

    # # Adjust R_1_omega_tmp due to BC Re from 0.1 to 0.045um based on Eq. 1 & Table S1 in He et al.2018 (GRL)
    R_1_omega_010_ulv = R_1_omega_tmp[0:1]  # enhancement for Re=0.1um, visible
    R_1_omega_010_vis = R_1_omega_tmp[1:11]  # enhancement for Re=0.1um, visible
    R_1_omega_010_nir = R_1_omega_tmp[11:16]  # enhancement for Re=0.1um, NIR

    # ultraviolet
    f1 = 0.1 / 0.05
    f2 = Rv / 0.05
    R_1_omega_005_ulv = (R_1_omega_010_ulv / f1 ** m_wvl[0]) ** (f1 ** -n_wvl[0])
    # visible
    R_1_omega_005_vis = (R_1_omega_010_vis / f1 ** m_wvl[1]) ** (f1** -n_wvl[1])
    # NIR
    R_1_omega_005_nir = (R_1_omega_010_nir / f1 ** m_wvl[2]) ** (f1 ** -n_wvl[2])

    R_1_omega_ulv = f2 ** m_wvl[0] * (R_1_omega_005_ulv**(f2 **n_wvl[0]))
    R_1_omega_vis = f2 ** m_wvl[1] * (R_1_omega_005_vis**(f2 **n_wvl[1]))
    R_1_omega_nir = f2 ** m_wvl[2] * (R_1_omega_005_nir**(f2 **n_wvl[2]))


    R_1_omega_tmp = np.concatenate([R_1_omega_ulv, R_1_omega_vis, R_1_omega_nir, [1.0], [1.0]])

    # Interpolate in a logscale field
    logR_1_omega_tmp = np.log10(R_1_omega_tmp)
    interpolator = PchipInterpolator(R_wvl_center, logR_1_omega_tmp)
    logR_intp = interpolator(wvl)
    R_intp = 10.0**logR_intp

    # BC does not reduce snow absorption
    R_intp[R_intp < 1.0] = 1.0
    # lambda>1.2um, no BC enhancement
    R_intp[wvl >= 1.2] = 1.0
    R_1_omega = R_intp

    # new 1-omega (single-scattering coalbedo) for entire BC-snow internal mixture
    tmp_1_omega_snw = (1.0 - omega_snw) * R_1_omega
    #
    # Smoothing the enhanced 1-omega for <1.2um
    window_size = 5
    ind = wvl < 5.1
    if np.any(ind):
        # 5-point moving average smooth
        tmp_1_omega_sm = np.convolve(np.log10(tmp_1_omega_snw[ind]), np.hanning(window_size)/np.hanning(window_size).sum(), mode='same')
        tmp_1_omega_snw[ind] = 10.0**tmp_1_omega_sm

    # new omega for entire BC-snow internal mixture
    omega_snw_enh = 1.0 - tmp_1_omega_snw

    return omega_snw_enh

